import { YgCore } from 'yg-core';

/**
 * Единая точка входа в SDK площадки.
 *
 * Живёт отдельным модулем, а не внутри локализации или звука, потому что нужен
 * обоим и ещё рекламе, сохранениям и рейтингам. Создаётся ровно один раз:
 * второй экземпляр завёл бы вторую инициализацию SDK и второй сторожевой
 * таймер готовности.
 *
 * Отдельно про `core.audio`. Это ЕДИНСТВЕННЫЙ шлюз вынужденного молчания
 * на всю игру: уход со вкладки, потеря фокуса окна и показ рекламы (пп. 1.3
 * и 4.7). Раньше звук игры держал свой собственный экземпляр `AudioGate`,
 * и получалось два независимых шлюза: реклама глушила тот, что внутри
 * каркаса, а звучал другой. То есть на ролике игра продолжала бы играть
 * музыку — прямое нарушение п. 4.7, которое никак не проявлялось только
 * потому, что реклама ещё не подключена.
 */
/**
 * Пауза игры на время рекламы (п. 4.7). Звук глушит сам каркас, а остановить
 * мир (клиенты, время дня, анимации) может только игра: App подставляет сюда
 * свои обработчики. Каркас читает их в момент показа, поэтому их можно
 * назначить уже после создания ядра.
 */
export const adHooks: { onSuspend?: () => void; onResume?: () => void } = {};
export const core = new YgCore({ ads: adHooks });
