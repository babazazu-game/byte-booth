/**
 * Реклама.
 *
 * Механика показа живёт в каркасе (`core.ads`), здесь — ПРАВИЛА: где именно
 * игра имеет право звать рекламу и что делает, когда её не показали.
 *
 * ── ДВА ПРАВИЛА, КОТОРЫЕ НЕЛЬЗЯ НАРУШАТЬ ────────────────────────────────
 *
 * 1. Награда за ролик — БОНУС, а не условие прогресса (п. 4.5.2). Всю игру
 *    можно пройти, не посмотрев ни одного ролика: бесплатные отмены и
 *    подсказки есть на каждом уровне, а за рекламу докупается сверх них.
 *    Косметика в магазине по той же причине — косметика.
 *
 * 2. Полноэкранная реклама — только в логической паузе (п. 4.4), между
 *    уровнями, и строго по нажатию игрока. Никогда поверх партии.
 *
 * ── ЧТО ПРОИСХОДИТ БЕЗ SDK ──────────────────────────────────────────────
 *
 * На локальной машине площадки нет, и `core.ads` честно отвечает «не показал».
 * Раньше награда в таком случае выдавалась сразу — иначе магазин было нечем
 * проверить. Теперь так делать нельзя: это ровно то поведение, за которое
 * прилетает отказ, если случайно уедет в релиз. Поэтому для разработки есть
 * явный флаг `PRETEND_ADS_WATCHED` в `dev.ts`: он подменяет ответ площадки
 * и виден в одном месте вместе с остальными отладочными переключателями.
 */

import { core } from './core.ts';
import { PRETEND_ADS_WATCHED } from './dev.ts';

/**
 * Показать ролик за награду. `true` — площадка засчитала просмотр.
 *
 * Награда выдаётся строго по этому ответу. Каркас берёт его из `onRewarded`,
 * а не из `onClose`: закрытие приходит и при досрочном выходе, когда просмотр
 * не засчитан.
 */
export async function watchRewarded(): Promise<boolean> {
  const shown = await core.ads.rewarded();
  if (shown) return true;
  return PRETEND_ADS_WATCHED;
}

/**
 * Полноэкранная реклама между уровнями.
 *
 * Частоту держит каркас: минимальный интервал между показами, и счётчик
 * двигается только при ФАКТИЧЕСКОМ показе. Здесь ничего решать не надо —
 * зовём на каждом переходе, площадка сама решит, показывать ли.
 *
 * Ответ игре не нужен: показали рекламу или нет, следующий уровень
 * начинается одинаково.
 */
export async function interstitialBetweenLevels(): Promise<void> {
  await core.ads.interstitial();
}

/**
 * Sticky-баннер: включается один раз за сессию и висит дальше сам.
 *
 * ── ПОЧЕМУ ОН ВООБЩЕ ЕСТЬ ───────────────────────────────────────────────
 *
 * Это единственный формат, который приносит что-то с игрока, ни разу не
 * посмотревшего ролик, — а таких большинство. Полноэкранная показывается
 * между уровнями и редко, вознаграждаемая только по своей воле.
 *
 * ── ПОЧЕМУ НЕ ПРЯЧЕМ НА ВРЕМЯ ПАРТИИ ────────────────────────────────────
 *
 * Партия — это и есть вся игра: спрятать баннер на время партии значит
 * не показывать его никогда. Площадка размещает sticky сама, вне канваса,
 * и это её штатный формат — перекрытия интерфейса тут быть не должно.
 *
 * ── ЧЕГО МЫ ПРО НЕГО НЕ ЗНАЕМ ───────────────────────────────────────────
 *
 * Документация не говорит, сдвигает баннер вьюпорт или ложится поверх, и
 * размеров не сообщает. Отдельного резерва места под него мы не закладываем:
 * если он сдвинет вьюпорт, за нас всё сделает наблюдатель за контейнером
 * в `main.ts` — раскладка пересчитывается от фактического размера. ЭТО НАДО
 * ПОСМОТРЕТЬ ГЛАЗАМИ на черновике в Консоли, прежде чем публиковать.
 *
 * Опция «Использовать API для показа sticky-баннера» должна быть включена
 * в Консоли разработчика. Без неё вызов вернёт `ADV_IS_NOT_CONNECTED`, и
 * это не ошибка игры — просто галочка не стоит.
 */
let bannerAsked = false;

export async function showStickyBanner(): Promise<void> {
  if (bannerAsked) return;
  bannerAsked = true;
  await core.ads.showBanner();
}
